LENGTH_GUIDES = {
    "short": (
        "只写 60—100 个中文字符。"
        "最多 2 个短段落，每段最多 2 句话。"
        "不要解释背景，不要列举多个卖点，不要写结尾总结。"
    ),
    "medium": (
        "写 180—300 个中文字符。"
        "使用 2—3 个短段落，每段最多 3 句话。"
        "只保留一个核心场景和 2—3 个重点。"
    ),
    "long": (
        "写 400—650 个中文字符。"
        "使用 4—5 个短段落。"
        "可以包含场景、核心价值、细节与自然的结尾。"
    ),
}


def build_copywriting_prompt(
    topic: str,
    platform: str,
    style: str,
    audience: str,
    length: str,
) -> str:
    platform_guide = PLATFORM_GUIDES.get(
        platform,
        PLATFORM_GUIDES["全平台通用"],
    )

    length_guide = LENGTH_GUIDES.get(
        length,
        LENGTH_GUIDES["medium"],
    )

    return f"""
你是一名擅长中文社交媒体内容创作的文案作者。

请根据以下要求生成一篇可直接发布的中文文案：

主题：{topic}
发布平台：{platform}
内容风格：{style}
目标受众：{audience}
平台表达要求：{platform_guide}
长度要求：{length_guide}

要求：
1. 紧扣主题，不要编造具体产品参数、优惠价格或虚假使用经历。
2. 文案必须符合指定的平台、风格和目标受众。
3. 长度要求优先级最高，必须严格执行；不要为了写完整而超出长度。
4. 写完后先自行检查字数、句数和段落数，再输出最终文案。
5. 内容应有清晰重点，避免空泛套话。
6. 不要解释创作过程。
7. 必须严格按照以下格式输出，不要添加任何额外说明：

标题：一句吸引人的标题

正文：
可直接发布的正文内容

标签：#标签1 #标签2 #标签3

8. 标题不超过 25 个中文字符。
9. 生成 3—5 个与主题、平台和内容相关的标签。
10. “长度要求”只计算正文，不计算标题和标签。
11. 不要使用 Markdown 标题符号或加粗符号。
""".strip()

OPTIMIZE_GOAL_GUIDES = {
    "更简洁": (
        "删除重复、空泛和无效表达，保留核心信息。"
        "让内容更短、更清楚、更容易快速阅读。"
    ),
    "更有吸引力": (
        "增强开头吸引力、核心卖点和行动引导。"
        "表达要自然可信，避免夸张承诺和标题党。"
    ),
    "更专业": (
        "让结构更清晰、措辞更准确、表达更有逻辑。"
        "保持可信、克制的语气，避免过度营销。"
    ),
    "更适合小红书": (
        "使用真实、亲切、有分享感的表达。"
        "突出场景、体验和实用价值，可适量使用 emoji。"
        "结尾添加 3—5 个相关话题标签。"
    ),
}


def build_optimize_prompt(content: str, goal: str) -> str:
    goal_guide = OPTIMIZE_GOAL_GUIDES.get(
        goal,
        OPTIMIZE_GOAL_GUIDES["更简洁"],
    )

    return f"""
你是一名擅长中文社交媒体内容优化的文案编辑。

请根据用户选择的优化目标，改写下面的原始文案。

优化目标：{goal}
优化要求：{goal_guide}

原始文案：
{content}

要求：
1. 保留原文的核心事实、主题和主要信息，不要编造产品参数、价格、优惠、使用经历或数据。
2. 只输出优化后的完整文案，不要解释修改思路。
3. 不要使用 Markdown 标题符号、加粗符号或代码块。
4. 如果原文包含标题、正文、标签，请保留清晰结构。
5. 若优化目标为“更适合小红书”，可以优化或补充相关标签；其他目标不要强行添加标签。
""".strip()